using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text.Json;
using System.Text.RegularExpressions;

namespace UntamedManager.Core;

/// <summary>Exact ASA project/file folders only. Move rather than delete.
/// A completed repair proves local cache removal, not successful download or gameplay.</summary>
public static class LocalModRepair
{
    public sealed record Folder(string Relative,string FileIdentity);
    private static readonly string[] Trees={
        Path.Combine("ShooterGame","Binaries","Win64","ShooterGame","Mods","83374"),
        Path.Combine("ShooterGame","Mods","83374")
    };
    public static Folder[] Inspect(string installation,string project)
    {
        if(!Regex.IsMatch(project,@"\A[0-9]{5,12}\z"))throw new InvalidDataException("UM-MOD-REPAIR-ID");
        _=UntamedOperationCoordinator.ResourceKey(installation);
        string root=Path.GetFullPath(installation);
        var folders=new List<Folder>();
        foreach(string tree in Trees)
        {
            string full=Path.Combine(root,tree);
            _=UntamedOperationCoordinator.ResourceKey(full);
            FileAttributes attrs;
            try{attrs=File.GetAttributes(full);}
            catch(FileNotFoundException){continue;}
            catch(DirectoryNotFoundException){continue;}
            if((attrs&FileAttributes.Directory)==0||(attrs&FileAttributes.ReparsePoint)!=0)
                throw new InvalidDataException("UM-MOD-REPAIR-TREE-UNSAFE");
            foreach(string candidate in Directory.EnumerateFileSystemEntries(full,"*",SearchOption.TopDirectoryOnly))
            {
                if(!Regex.IsMatch(Path.GetFileName(candidate),"\\A"+project+@"_[0-9]{1,20}\z"))continue;
                attrs=File.GetAttributes(candidate);
                if((attrs&FileAttributes.Directory)==0||(attrs&FileAttributes.ReparsePoint)!=0)
                    throw new InvalidDataException("UM-MOD-REPAIR-FOLDER-UNSAFE");
                _=UntamedOperationCoordinator.ResourceKey(candidate);
                folders.Add(new(Path.GetRelativePath(root,candidate),StorePathIdentity.LocalDirectoryFingerprint(candidate)));
                if(folders.Count>64)throw new InvalidDataException("UM-MOD-REPAIR-FOLDER-LIMIT");
            }
        }
        return folders.OrderBy(x=>x.Relative,StringComparer.OrdinalIgnoreCase).ToArray();
    }
    public static int Quarantine(LocalMap map,string project,Folder[] expected,
        Action verifyStoppedAndOwned,UntamedOperationCoordinator coordinator)
    {
        ArgumentNullException.ThrowIfNull(verifyStoppedAndOwned);
        string root=Path.GetFullPath(map.InstallationPath);
        using var lease=coordinator.Acquire(root,UntamedOperationKind.Configuration);
        verifyStoppedAndOwned();
        if(!Inspect(root,project).SequenceEqual(expected))throw new InvalidOperationException("UM-MOD-REPAIR-CHANGED");
        if(expected.Length==0)return 0;
        string quarantine=Path.Combine(root,".obsidian-mod-quarantine",Guid.NewGuid().ToString("N"));
        _=UntamedOperationCoordinator.ResourceKey(quarantine);
        Directory.CreateDirectory(quarantine);
        _=UntamedOperationCoordinator.ResourceKey(quarantine);
        // Journal names/identities are generated by native Inspect, never renderer paths.
        using(var output=new FileStream(Path.Combine(quarantine,"manifest.json"),FileMode.CreateNew,FileAccess.Write,FileShare.None))
        {JsonSerializer.Serialize(output,new{mapId=map.Id,project,folders=expected});output.Flush(true);}
        var moved=new List<(string Original,string Target,string Identity)>();
        try
        {
            foreach(var item in expected)
            {
                verifyStoppedAndOwned();
                string source=Path.Combine(root,item.Relative);
                _=UntamedOperationCoordinator.ResourceKey(source);
                if(StorePathIdentity.LocalDirectoryFingerprint(source)!=item.FileIdentity)
                    throw new InvalidOperationException("UM-MOD-REPAIR-CHANGED");
                string target=Path.Combine(quarantine,moved.Count.ToString("D2"));
                _=UntamedOperationCoordinator.ResourceKey(target);
                if(moved.Count==0)lease.MarkMutationStarted();
                Directory.Move(source,target);
                moved.Add((source,target,item.FileIdentity));
                if(StorePathIdentity.LocalDirectoryFingerprint(target)!=item.FileIdentity)
                    throw new IOException("UM-MOD-REPAIR-MOVE-IDENTITY");
            }
            verifyStoppedAndOwned();
            if(Inspect(root,project).Length!=0)throw new IOException("UM-MOD-REPAIR-REMAINS");
            File.WriteAllText(Path.Combine(quarantine,"complete"),"1");
            lease.Complete();
            return moved.Count;
        }
        catch
        {
            // Roll back only an exact directory moved by this invocation,
            // with fresh stop proof. If uncertain, leave the durable journal
            // and preserved directory intact; never delete files or replay.
            if(moved.Count>0)
            {
                verifyStoppedAndOwned();
                foreach(var item in moved.AsEnumerable().Reverse())
                {
                    _=UntamedOperationCoordinator.ResourceKey(item.Original);
                    if(File.Exists(item.Original)||Directory.Exists(item.Original)||
                        StorePathIdentity.LocalDirectoryFingerprint(item.Target)!=item.Identity)
                        throw new IOException("UM-MOD-REPAIR-ROLLBACK-UNCERTAIN");
                    Directory.Move(item.Target,item.Original);
                }
                if(!Inspect(root,project).SequenceEqual(expected))
                    throw new IOException("UM-MOD-REPAIR-ROLLBACK-UNCERTAIN");
                lease.Complete();
            }
            throw;
        }
    }
}
